function buildCatalog() {
  const out = [];
  for (const group of CATEGORIES) {
    group.items.forEach((entry, i) => {
      out.push({
        id: 'sfx_' + group.cat.replace(/[^A-Za-z0-9]+/g, '_') + '_' + i,
        name: entry[0],
        cat: group.cat,
        model: entry[1] || entry[0],
        isWord: false
      });
    });
  }
  return out;
}

/* Guarantee a contiguous, duplicate-free, fully-populated suite of 2,500 items. */
function normalize(catalog, perCategory) {
  const seen = new Set();
  const counts = {};
  const out = [];
  for (const item of catalog) {
    if (seen.has(item.name)) continue;
    counts[item.cat] = counts[item.cat] || 0;
    if (counts[item.cat] >= perCategory) continue;
    seen.add(item.name);
    counts[item.cat]++;
    out.push(item);
  }
  return out;
}
const SFX_CATALOG = normalize(buildCatalog(), 100);

module.exports = { CATEGORIES, SFX_CATALOG, buildCatalog };
